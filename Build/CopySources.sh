#!/usr/bin/env bash
# Usage: bash Build/CopySources.sh [settings-path]
# Section format: [source-directory -> destination-directory]
# .cs paths are relative to the source directory and copied into a Generated/ directory

set -euo pipefail

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
settings="${1:-ExportSettings.ini}"
[[ "$settings" = /* || "$settings" =~ ^[A-Za-z]: ]] || settings="$repo_root/$settings"
fail() { printf '%s\n' "$*" >&2; exit 1; }
[[ -f "$settings" ]] || fail "Settings file not found: $settings"

relative_path() {
    local value="${1//\\//}"
    [[ -n "$value" && "$value" != /* && "$value" != *:* &&
       "/$value/" != */../* && "/$value/" != */./* && "$value" != *//* && "$value" != */ ]] ||
        fail "Expected a relative path without traversal: $1"
    printf '%s' "$value"
}

trim() {
    local value="$1"
    value="${value#"${value%%[![:space:]]*}"}"
    value="${value%"${value##*[![:space:]]}"}"
    printf '%s' "$value"
}

declare -a sources=() outputs=() namespaces=()
declare -A seen=()
destination=''
source_directory=''
line_number=0
while IFS= read -r line || [[ -n "$line" ]]; do
    line_number=$((line_number + 1))
    line="${line#$'\xef\xbb\xbf'}"
    line="$(trim "$line")"
    [[ -z "$line" || "$line" = \;* || "$line" = \#* ]] && continue
    if [[ "$line" =~ ^\[([^]]+)\]$ ]]; then
        section="${BASH_REMATCH[1]}"
        [[ "$section" == *'->'* && "${section#*->}" != *'->'* ]] ||
            fail "Expected [source-directory -> destination-directory] at line $line_number"
        source_directory="$(relative_path "$(trim "${section%%->*}")")"
        destination_directory="$(relative_path "$(trim "${section#*->}")")"
        [[ -d "$repo_root/$source_directory" ]] ||
            fail "Source directory not found at line $line_number: $source_directory"
        destination="$repo_root/$destination_directory/Generated"
        namespace="${destination_directory##*/}"
        [[ "$namespace" =~ ^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$ ]] ||
            fail "Invalid destination namespace: $namespace"
        continue
    fi
    [[ -n "$destination" ]] || fail "Source before destination section at line $line_number"
    relative="$(relative_path "$line")"
    [[ "${relative,,}" = *.cs ]] || fail "Expected a .cs source: $relative"
    source="$repo_root/$source_directory/$relative"
    [[ -f "$source" ]] || fail "Source not found at line $line_number: $source_directory/$relative"
    output="$destination/${relative##*/}"
    key="${output,,}"
    [[ -z "${seen[$key]+present}" ]] || fail "Duplicate destination: $output"
    seen[$key]=1
    sources+=("$source") outputs+=("$output") namespaces+=("$namespace")
done < "$settings"

# Validate all paths before writing. Stage each transformed file before replacing it.
temp_file=''
trap '[[ -z "$temp_file" ]] || rm -f -- "$temp_file"' EXIT
for i in "${!sources[@]}"; do
    output="${outputs[$i]}"
    mkdir -p -- "$(dirname -- "$output")"
    temp_file="$(mktemp "${output}.XXXXXX")"
    awk -v ns="${namespaces[$i]}" '
        BEGIN {
            print "//------------------------------------------------------------------------------"
            print "// <auto-generated>"
            print "//     This code was generated by a tool."
            print "//"
            print "//     Changes to this file may cause incorrect behavior and will be lost if"
            print "//     the code is regenerated."
            print "// </auto-generated>"
            print "//------------------------------------------------------------------------------"
        }
        {
            sub(/\r$/, "")
            if (NR == 1) sub(/^\357\273\277/, "")
            if ($0 ~ /^[\t ]*namespace[\t ]+[A-Za-z_][A-Za-z0-9_.]*[\t ]*([;{]|$)/) {
                match($0, /^[\t ]*namespace[\t ]+/)
                prefix = substr($0, 1, RLENGTH)
                rest = substr($0, RLENGTH + 1)
                sub(/^[A-Za-z_][A-Za-z0-9_.]*/, "", rest)
                $0 = prefix ns rest
            }
            print
        }
    ' "${sources[$i]}" > "$temp_file"
    if [[ -f "$output" ]] && cmp -s -- "$temp_file" "$output"; then
        rm -f -- "$temp_file"
    else
        mv -f -- "$temp_file" "$output"
        printf 'Copied %s\n' "$output"
    fi
    temp_file=''
done
printf 'Processed %s source file(s).\n' "${#sources[@]}"
