# Copies source snapshots without adding dependencies to destination projects.
# Reads ../ExportSettings.ini (or -SettingsPath). Format:
#   [DevTools/DevTools]
#   Core/Utils/Ref.cs

[CmdletBinding()]
param([string]$SettingsPath = 'ExportSettings.ini')

$ErrorActionPreference = 'Stop'
$repoRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Get-RelativePath([string]$Value) {
    $value = $Value.Replace('\', '/').Trim()
    if (!$value -or $value.StartsWith('/') -or $value.Contains(':') -or
        ($value.Split('/') | Where-Object { $_ -eq '..' -or $_ -eq '.' -or $_ -eq '' })) {
        throw "Expected a relative path without traversal: $Value"
    }
    return $value
}

if (![IO.Path]::IsPathRooted($SettingsPath)) {
    $SettingsPath = Join-Path $repoRoot $SettingsPath
}
if (!(Test-Path -LiteralPath $SettingsPath -PathType Leaf)) {
    throw "Settings file not found: $SettingsPath"
}

$jobs = @()
$outputs = @{}
$destination = $null
$lineNumber = 0
foreach ($rawLine in [IO.File]::ReadAllLines($SettingsPath)) {
    $lineNumber++
    $line = $rawLine.Trim()
    if (!$line -or $line.StartsWith(';') -or $line.StartsWith('#')) { continue }
    if ($line -match '^\[([^\]]+)\]$') {
        $section = Get-RelativePath $Matches[1]
        $destination = Join-Path $repoRoot "$section/Generated"
        $namespace = ($section -split '/')[-1]
        if ($namespace -notmatch '^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$') {
            throw "Invalid destination namespace: $namespace"
        }
        continue
    }
    if (!$destination) { throw "Source before destination section at line $lineNumber" }
    $relative = Get-RelativePath $line
    if ([IO.Path]::GetExtension($relative) -ne '.cs') { throw "Expected a .cs source: $relative" }
    $source = Join-Path $repoRoot $relative
    if (!(Test-Path -LiteralPath $source -PathType Leaf)) {
        $source = Join-Path $repoRoot "SmashTools/$relative"
    }
    if (!(Test-Path -LiteralPath $source -PathType Leaf)) {
        throw "Source not found at line ${lineNumber}: $relative (checked repository and SmashTools)"
    }
    $output = Join-Path $destination ([IO.Path]::GetFileName($relative))
    if ($outputs.ContainsKey($output)) { throw "Duplicate destination: $output" }
    $outputs[$output] = $true
    $content = [IO.File]::ReadAllText($source).Replace("`r`n", "`n")
    $pattern = '(?m)^([\t ]*namespace[\t ]+)[A-Za-z_][A-Za-z0-9_.]*(?=[\t ]*(?:[;{]|$))'
    $content = [regex]::Replace($content, $pattern, ('${1}' + $namespace))
    $header = @(
        '//------------------------------------------------------------------------------'
        '// <auto-generated>'
        '//     This code was generated by a tool.'
        '//'
        '//     Changes to this file may cause incorrect behavior and will be lost if'
        '//     the code is regenerated.'
        '// </auto-generated>'
        '//------------------------------------------------------------------------------'
    ) -join "`n"
    $content = $header + "`n" + $content
    if (!$content.EndsWith("`n")) { $content += "`n" }
    $jobs += [pscustomobject]@{ Output = $output; Content = $content }
}

foreach ($job in $jobs) {
    if ((Test-Path -LiteralPath $job.Output -PathType Leaf) -and
        [IO.File]::ReadAllText($job.Output) -ceq $job.Content) { continue }
    [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($job.Output)) | Out-Null
    [IO.File]::WriteAllText($job.Output, $job.Content, $utf8)
    Write-Output "Copied $($job.Output)"
}
Write-Output "Processed $($jobs.Count) source file(s)."
